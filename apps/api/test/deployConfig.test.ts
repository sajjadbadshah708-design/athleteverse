// Guards the deployment files against drift (SRS 3.3, Table 7, Table 8). Findings F1 to F3 in docs/DEPLOY.md explain why.
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';

const root = new URL('../../../', import.meta.url);
const read = (path: string) => readFileSync(new URL(path, root), 'utf8');

interface RenderService {
  plan: string;
  healthCheckPath: string;
  buildCommand: string;
  startCommand: string;
  envVars: { key: string; value?: string; sync?: boolean; generateValue?: boolean }[];
}
const service = (parse(read('render.yaml')) as { services: RenderService[] }).services[0]!;
const env = (key: string) => service.envVars.find((e) => e.key === key);

describe('render.yaml', () => {
  it('runs on the free plan and migrates during the build', () => {
    expect(service.plan).toBe('free');
    expect(service.buildCommand).toContain('npm run db:deploy');
    expect(service.buildCommand).toContain('--include=dev'); // the prisma CLI is a dev dependency
  });

  it('starts node directly so SIGTERM reaches the server and shutdown is graceful (finding F7)', () => {
    expect(service.startCommand).toMatch(/^exec node --import tsx /);
    expect(service.startCommand).not.toContain('npm');
  });

  it('health check is liveness only: it must never query the database (finding F2)', () => {
    expect(service.healthCheckPath).toBe('/api/v1/health');
    expect(service.healthCheckPath).not.toMatch(/db/i);
  });

  it('keeps secrets out of the file', () => {
    for (const key of ['DATABASE_URL', 'DIRECT_URL']) {
      expect(env(key)?.sync, key).toBe(false);
      expect(env(key)?.value, key).toBeUndefined();
    }
    for (const key of ['JOB_SECRET', 'JWT_SECRET', 'OTP_PEPPER']) {
      expect(env(key), key).toMatchObject({ generateValue: true }); // generated by Render, never committed
      expect(env(key)?.value, key).toBeUndefined();
    }
    for (const key of ['MAIL_PROVIDER', 'MAIL_API_KEY', 'MAIL_FROM', 'WEB_BASE_URL']) {
      expect(env(key)?.sync, key).toBe(false); // entered in the dashboard
      expect(env(key)?.value, key).toBeUndefined();
    }
  });

  it('runs database jobs every 30 minutes so the free Neon quota lasts the month (decision Q5)', () => {
    expect(env('JOB_DB_INTERVAL_MINUTES')?.value).toBe('30');
  });

  it('starts in production mode with the spike endpoint off', () => {
    expect(env('NODE_ENV')?.value).toBe('production');
    expect(env('ENABLE_SPIKES')?.value).toBe('false');
  });
});

describe('apps/web/vercel.json (web app and API in one Vercel project, decision 2026-11-17)', () => {
  const config = JSON.parse(read('apps/web/vercel.json')) as Record<string, unknown>;

  it('installs from the repository root, generates Prisma, builds the web app, then assembles the Build Output', () => {
    expect(config.framework).toBeNull(); // the Build Output API decides what is served, not a framework preset
    expect(config.installCommand).toBe('cd ../.. && npm ci');
    expect(config.buildCommand).toBe('cd ../.. && npm run db:generate && npm run build -w @athleteverse/web && node scripts/vercel-output.mjs');
  });

  it('has no rewrite to an external API host and no static output directory (scripts/vercel-output.mjs owns routing)', () => {
    expect(config).not.toHaveProperty('rewrites');
    expect(config).not.toHaveProperty('outputDirectory');
  });
});

describe('scripts/vercel-output.mjs', () => {
  const script = read('scripts/vercel-output.mjs');

  it('applies migrations on production builds only, never on preview builds', () => {
    expect(script).toContain("process.env.VERCEL_ENV === 'production'");
    expect(script).toContain('npm run db:deploy');
  });

  it('routes /api to the function before the single-page fallback, on Node 22', () => {
    expect(script.indexOf("dest: '/api'")).toBeGreaterThan(-1);
    expect(script.indexOf("dest: '/api'")).toBeLessThan(script.indexOf("dest: '/index.html'"));
    expect(script).toContain("runtime: 'nodejs22.x'");
    expect(script).toContain("'@prisma/client', '.prisma/client'"); // kept outside the bundle and copied beside it
  });
});

describe('.github/workflows/tick.yml', () => {
  const workflow = parse(read('.github/workflows/tick.yml')) as {
    on: { schedule: { cron: string }[] };
    jobs: { tick: { steps: { run?: string; env?: Record<string, string> }[] } };
  };
  const step = workflow.jobs.tick.steps[0]!;

  it('runs every 30 minutes: on Vercel nothing needs keeping awake, and the free Neon database can sleep (decision Q5)', () => {
    expect(workflow.on.schedule[0]!.cron).toBe('*/30 * * * *');
  });

  it('authenticates with the secret header, taken from repository secrets, and fails when a job failed', () => {
    expect(step.env).toEqual({ API_URL: '${{ secrets.API_URL }}', JOB_SECRET: '${{ secrets.JOB_SECRET }}' });
    expect(step.run).toContain('/api/jobs/tick');
    expect(step.run).toContain('X-Job-Secret');
    expect(step.run).toContain("jq -e '.ok == true'");
  });
});
